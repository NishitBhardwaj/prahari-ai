"""
Evidence Engine — generates forensic assets and physical seizures tied to cases.
Links evidence items (weapons, drugs, devices) to crimes and accused.

Depends on: master, crime, media
"""

from typing import Dict, List
import pandas as pd
import numpy as np

from engines.base_engine import BaseEngine
from schemas.base import generate_id


class EvidenceEngine(BaseEngine):

    @property
    def name(self) -> str:
        return "evidence"

    @property
    def dependencies(self) -> List[str]:
        return ["master", "crime", "media"]

    def generate(self) -> Dict[str, pd.DataFrame]:
        self.logger.info("Generating Evidence and Forensics...")

        cases = self.store.get("cases")
        media = self.store.get("media_metadata_all")
        
        if cases.empty:
            return {}

        evidence_records = []
        forensic_records = []

        # Find media assets that are evidence images (generated by media engine)
        evidence_media = []
        if not media.empty:
            evidence_media = media[media["media_sub_type"].str.startswith("Evidence -", na=False)]

        case_list = cases.to_dict("records")
        
        for c in case_list:
            case_id = c["case_id"]
            crime_head = c["crime_head_name"]
            
            # Not all cases have recovered evidence
            if self.rng.random() > 0.6:
                continue

            # Determine type of evidence based on crime
            e_type, e_subtype, desc = self._get_evidence_type(crime_head)
            
            evd_id = generate_id("EVD-")
            
            # Find a matching media image if available
            media_id = ""
            if len(evidence_media) > 0:
                # Try to find a matching type
                match = evidence_media[evidence_media["media_sub_type"].str.contains(e_subtype, case=False, na=False)]
                if not match.empty:
                    media_id = match.sample(n=1).iloc[0]["media_id"]
                else:
                    media_id = evidence_media.sample(n=1).iloc[0]["media_id"]

            evidence_records.append({
                "evidence_id": evd_id,
                "case_id": case_id,
                "evidence_type": e_type,
                "sub_type": e_subtype,
                "description": desc,
                "seizure_date": c["date_of_report"],
                "storage_location": "Malkhana",
                "chain_of_custody_status": "Secure",
                "media_id": media_id
            })

            # Edge linking evidence to case
            self.store.add_edge(evd_id, "COLLECTED_IN", case_id, {"type": e_type})

            # Generate Forensic Report for certain types
            if e_type in ["Biological", "Digital", "Ballistics"]:
                forensic_records.append({
                    "forensic_report_id": generate_id("FSL-"),
                    "evidence_id": evd_id,
                    "case_id": case_id,
                    "report_type": f"{e_type} Analysis",
                    "report_date": c["date_of_report"], # Simplification
                    "finding_summary": f"Positive match for {e_subtype} analysis.",
                    "expert_name": f"Dr. {self.rng.choice(['Rao', 'Reddy', 'Patil', 'Gowda'])}",
                    "is_conclusive": bool(self.rng.random() > 0.1)
                })

        self.logger.info(f"Generated {len(evidence_records)} evidence items and {len(forensic_records)} FSL reports.")

        return {
            "evidence": pd.DataFrame(evidence_records),
            "forensics": pd.DataFrame(forensic_records),
        }

    def _get_evidence_type(self, crime_head: str) -> tuple:
        """Return (Type, Subtype, Description) based on crime."""
        mapping = {
            "Murder": [
                ("Physical", "Knife", "Blood-stained machete"),
                ("Ballistics", "Pistol", "Country-made pistol, 9mm"),
                ("Biological", "Blood", "Blood samples from scene")
            ],
            "Assault": [
                ("Physical", "Knife", "Pocket knife"),
                ("Physical", "Blunt Object", "Iron rod")
            ],
            "Cyber Crime": [
                ("Digital", "Mobile", "Smartphone used for phishing"),
                ("Digital", "Laptop", "Laptop with scam scripts"),
                ("Digital", "Hard Drive", "External hard drive with data")
            ],
            "Narcotics": [
                ("Physical", "Drug", "100g of MDMA crystals"),
                ("Physical", "Drug", "2kg of Ganja"),
                ("Physical", "Cash", "Rs 50,000 cash proceeds")
            ],
            "Robbery": [
                ("Physical", "Knife", "Threatening weapon"),
                ("Physical", "Cash", "Recovered stolen cash"),
                ("Physical", "Jewelry", "Stolen gold chain")
            ],
            "Fraud": [
                ("Physical", "Document", "Forged property documents"),
                ("Physical", "Document", "Fake stamp papers"),
                ("Digital", "Laptop", "Computer used for forgery")
            ]
        }

        choices = mapping.get(crime_head, [("Physical", "Document", "Miscellaneous items")])
        idx = int(self.rng.integers(0, len(choices)))
        return choices[idx]
